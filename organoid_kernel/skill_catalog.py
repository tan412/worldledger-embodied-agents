def skill_catalog() -> dict:
    library = default_skill_library()
    return {
        "schema": "organoid-kernel.skill-catalog.v1",
        "skills": [library.get(name).to_dict() for name in library.names()],
        "dataset_sources": [source.to_dict() for source in dataset_skill_sources()],
    }
