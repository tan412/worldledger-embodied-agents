from .skills import Skill, SkillLibrary


def _skill(name: str, category: str, *,
           inputs=(), outputs=(), pre=(), post=(), clears=(),
           sensors=(), control="cartesian_position", objects=("*",),
           robots=("*",), evidence=(), description="") -> Skill:
    return Skill(
        name=name,
        category=category,
        input_states=tuple(inputs),
        output_states=tuple(outputs),
        preconditions=tuple(frozenset(option) for option in (pre or ((),))),
        postconditions=frozenset(post),
        clears=frozenset(clears),
        sensors=tuple(sensors),
        control_mode=control,
        object_kinds=tuple(objects),
        robot_types=tuple(robots),
        evidence_sources=tuple(evidence),
        description=description,
    )


